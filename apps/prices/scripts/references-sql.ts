// Turns docs/plans/u5-reference-candidates.csv into idempotent SQL that loads
// watch_references, reference_price_urls and price_sources. Pure (no I/O) so the
// tests run the exact SQL against the real migrations.

import { slugifyBrand, slugifyReference } from "../../../packages/shared/src/slug.ts";
import { readCsvObjects } from "../../registry/scripts/csv.ts";

/** Hosts that are authorised retailers rather than the brand's own site. */
export const RETAILER_HOSTS = new Set(["www.bucherer.com", "www.watches-of-switzerland.co.uk"]);

/** Adapter per host (units 6 and 7). Hosts without one get the brand slug as a placeholder key. */
export const ADAPTER_BY_HOST: Record<string, string> = {
  "www.cartier.com": "cartier",
  "www.breitling.com": "breitling",
  "www.longines.com": "longines",
  "www.tissotwatches.com": "tissot",
  "www.rado.com": "rado",
  "www.omegawatches.com": "omega",
  "www.oris.ch": "oris",
  "www.grand-seiko.com": "grand-seiko",
  "www.bucherer.com": "bucherer",
  "www.watches-of-switzerland.co.uk": "watches-of-switzerland-uk",
};

const MARKETS = [
  ["ch", "CH"],
  ["fr", "FR"],
  ["uk", "UK"],
  ["us", "US"],
] as const;

const q = (v: string | number | null | undefined): string =>
  v === null || v === undefined || v === "" ? "NULL" : typeof v === "number" ? String(v) : `'${String(v).replace(/'/g, "''")}'`;

export interface ReferencesSql {
  sql: string;
  references: number;
  urls: number;
  sources: number;
  skipped: string[];
}

export function buildReferencesSql(csvText: string): ReferencesSql {
  const rows = readCsvObjects(csvText);
  const out: string[] = [
    "-- Generated by apps/prices/scripts/import-references.ts from",
    "-- docs/plans/u5-reference-candidates.csv. Idempotent; local D1 only.",
    "-- Needs the registry seed (brands) and migrations 0005-0008 applied first.",
  ];
  const slugs = new Map<string, string>();
  const sources = new Map<string, { brand: string; market: string; source: string; adapter: string; host: string }>();
  const skipped: string[] = [];
  let urls = 0;
  for (const r of rows) {
    const refCode = (r.ref_code ?? "").trim();
    const brandName = (r.brand ?? "").trim();
    if (!refCode || !brandName) {
      skipped.push(`row without brand or ref_code: ${JSON.stringify(r).slice(0, 80)}`);
      continue;
    }
    const brand = slugifyBrand(brandName);
    const slug = slugifyReference(brand, refCode);
    const clash = slugs.get(slug);
    if (clash && clash !== refCode) throw new Error(`reference slug ${slug} used by ${clash} and ${refCode}`);
    slugs.set(slug, refCode);
    const diameter = Number(r.diameter_mm);
    const notes = [r.verified === "TRUE" ? "prices checked by Paul" : null, r.notes?.trim() || null]
      .filter(Boolean)
      .join("; ");
    out.push(
      `INSERT INTO watch_references (brand_id, slug, ref_code, family, name, case_material, diameter_mm, notes)
SELECT id, ${q(slug)}, ${q(refCode)}, ${q(r.family)}, ${q(r.name)}, ${q(r.material)}, ${Number.isFinite(diameter) && diameter >= 10 && diameter <= 80 ? diameter : "NULL"}, ${q(notes ? `u5: ${notes}` : null)}
  FROM brands WHERE slug = ${q(brand)}
ON CONFLICT(brand_id, ref_code) DO UPDATE SET family = excluded.family, name = excluded.name,
  case_material = excluded.case_material, diameter_mm = excluded.diameter_mm, notes = excluded.notes,
  updated_at = datetime('now');`,
    );
    for (const [col, market] of MARKETS) {
      const url = (r[`url_${col}`] ?? "").trim();
      if (!url) continue;
      const host = new URL(url).hostname;
      const source = `${RETAILER_HOSTS.has(host) ? "retailer" : "brand"}:${host}`;
      urls++;
      out.push(
        `INSERT INTO reference_price_urls (reference_id, market_code, source, url)
SELECT r.id, ${q(market)}, ${q(source)}, ${q(url)}
  FROM watch_references r JOIN brands b ON b.id = r.brand_id
 WHERE b.slug = ${q(brand)} AND r.ref_code = ${q(refCode)}
ON CONFLICT(reference_id, market_code, source) DO UPDATE SET url = excluded.url, active = 1,
  updated_at = datetime('now');`,
      );
      const key = `${brand}|${market}|${source}`;
      if (!sources.has(key)) sources.set(key, { brand, market, source, host, adapter: ADAPTER_BY_HOST[host] ?? brand });
    }
  }
  for (const s of sources.values()) {
    const pending = ADAPTER_BY_HOST[s.host] ? null : "adapter pending (unit 7)";
    out.push(
      `INSERT INTO price_sources (brand_id, market_code, source, method, adapter_key, notes)
SELECT id, ${q(s.market)}, ${q(s.source)}, 'fetch', ${q(s.adapter)}, ${q(pending)}
  FROM brands WHERE slug = ${q(s.brand)}
ON CONFLICT(brand_id, market_code, source, method) DO UPDATE SET adapter_key = excluded.adapter_key,
  notes = COALESCE(excluded.notes, notes);`,
    );
  }
  return { sql: out.join("\n") + "\n", references: slugs.size, urls, sources: sources.size, skipped };
}
